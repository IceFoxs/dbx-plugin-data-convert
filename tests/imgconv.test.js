/*
 * 图片 ↔ Base64 纯逻辑回归：node tests/imgconv.test.js
 *
 * 重点是三类容易翻车的地方：
 *   1. 分块编解码的结果必须和整段一致（大文件尤甚）；
 *   2. 裸 Base64 的现实变体（换行、url-safe、缺 padding、带引号/前缀）都要认；
 *   3. 体积上限与性能——10 MB 是允许的上限，不能让主线程卡成 PPT。
 */
