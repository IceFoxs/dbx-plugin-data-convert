test('SVG（裸 <svg> 与带 XML 声明）', function () {
    var enc = function (s) {
        var b = new Uint8Array(s.length);
        for (var i = 0; i < s.length; i++) b[i] = s.charCodeAt(i) & 0xff;
        return b;
    };
    assert.strictEqual(I.sniffMime(enc('<svg xmlns="http://www.w3.org/2000/svg"></svg>')), 'image/svg+xml');
    assert.strictEqual(I.sniffMime(enc('<?xml version="1.0"?><svg></svg>')), 'image/svg+xml');
    assert.strictEqual(I.sniffMime(enc('  \n<svg width="1"/>')), 'image/svg+xml');
});

test('SVG 带 BOM / DOCTYPE / 注释也认', function () {
    var enc = function (s) {
        var b = new Uint8Array(s.length);
        for (var i = 0; i < s.length; i++) b[i] = s.charCodeAt(i) & 0xff;
        return b;
    };
    var withBom = function (s) {
        var body = enc(s);
        var b = new Uint8Array(body.length + 3);
        b.set([0xef, 0xbb, 0xbf]);
        b.set(body, 3);
        return b;
    };
    // 真正的 UTF-8 BOM 是三个字节 EF BB BF，不是 U+FEFF 的低位
    assert.strictEqual(I.sniffMime(withBom('<svg></svg>')), 'image/svg+xml');
    assert.strictEqual(I.sniffMime(enc('<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN"><svg></svg>')), 'image/svg+xml');
    assert.strictEqual(I.sniffMime(enc('<!-- generated by figma -->\n<svg viewBox="0 0 1 1"></svg>')), 'image/svg+xml');
});

