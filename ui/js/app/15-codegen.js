// 编辑器懒创建：第一次进这一页才初始化，冷启动不为用不到的页面付代价。
// 用 linkTextareaToEditor 桥接 .value，既有逻辑（含冒烟用例）不用改成 getValue/setValue。
function ensureCodeEditors() {
    if (codeInputEditor) return;
    const config = Object.assign({}, commonConfig, {
        mode: CODE_INPUT_MODE[codeSource],
        placeholder: codeInput.placeholder || '',
        // 沿用其他页面的约定：⌘/Ctrl + Enter 就地重跑，不做格式转换
        extraKeys: Object.assign({}, commonConfig.extraKeys, {
            'Cmd-Enter': () => codeRegen(),
            'Ctrl-Enter': () => codeRegen()
        })
    });
    codeInputEditor = CodeMirror.fromTextArea(codeInput, config);
    codeOutputEditor = CodeMirror.fromTextArea(codeOutput, Object.assign({}, config, {
        readOnly: true,
        placeholder: codeOutput.placeholder || '',
        mode: CODE_OUTPUT_MODE[codeLang]
    }));
    codeInputEditor.on('change', () => {
        const next = codeInputEditor.getValue();
        if (codeInput.value !== next) codeInput.value = next;
        codeSchedule();
    });
    linkTextareaToEditor(codeInput, codeInputEditor);
    linkTextareaToEditor(codeOutput, codeOutputEditor);
    // 懒创建时主题可能已经切过，补一次，避免新编辑器停在亮色主题
    syncEditorTheme();
}

// 源格式决定输入的高亮语言，目标语言决定输出的高亮语言；
// 顺便把空态提示同步过去——CodeMirror 不认 textarea 的 placeholder 属性
function codeSyncModes() {
    if (!codeInputEditor) return;
    codeInputEditor.setOption('mode', CODE_INPUT_MODE[codeSource] || 'text/plain');
    codeOutputEditor.setOption('mode', CODE_OUTPUT_MODE[codeLang] || 'text/plain');
    codeInputEditor.setOption('placeholder', codeInput.placeholder || '');
    codeOutputEditor.setOption('placeholder', codeOutput.placeholder || '');
}

function codeErrorText(res) {
    if (res.code === 'empty') return genT('genErrEmpty');
    if (res.code === 'too-large') return genT('genErrTooLarge');
    if (res.code === 'no-ddl') return genT('genErrNoDdl');
    return genT('genErrBadJson');
}

function codeSetTip(text, cls) {
    codeTip.textContent = text || '';
    codeTip.className = 'compare-tip' + (cls ? ' ' + cls : '');
}

function codeApplySourceUi() {
    codeSourceTabs.querySelectorAll('.compare-tab').forEach((tab) => {
        tab.classList.toggle('active', tab.dataset.source === codeSource);
    });
    codeLangTabs.querySelectorAll('.compare-tab').forEach((tab) => {
        tab.classList.toggle('active', tab.dataset.lang === codeLang);
    });
    codeJsonSamples.classList.toggle('is-hidden', codeSource !== 'json');
    codeDdlSamples.classList.toggle('is-hidden', codeSource !== 'ddl');
    codeInLabel.textContent = genT(codeSource === 'json' ? 'genInputJsonTitle' : 'genInputDdlTitle');
    codeInput.placeholder = genT(codeSource === 'json' ? 'genPlaceholderJson' : 'genPlaceholderDdl');
    codeOutput.placeholder = genT('genEmpty');
    codeRoot.placeholder = genT('genRootPlaceholder');
    codeInBadge.textContent = codeSource === 'json' ? 'JSON' : 'DDL';
    codeOutBadge.textContent = CODE_LANG_LABEL[codeLang];
    codeSyncModes();
    if (codeLast) {
        codeSetTip(genT('genTipOk')
            .replace('{t}', String(codeLast.types))
            .replace('{f}', String(codeLast.fields)), 'ok');
    } else {
        codeSetTip(genT('genTipIdle'));
    }
}

function codeIdle() {
    codeOutput.value = '';
    codeOutput.classList.remove('has-content');
    codeOutSize.textContent = '';
    codeLast = null;
    codeSetTip(genT('genTipIdle'));
}

function codeRegen() {
    const text = codeInput.value;
    if (!text.trim()) {
        codeIdle();
        return;
    }
    if (!window.DBXCodegen) {
        codeSetTip(genT('genErrBadJson'), 'err');
        return;
    }
    const res = window.DBXCodegen.generate(text, {
        source: codeSource,
        lang: codeLang,
        rootName: codeRoot.value.trim()
    });
    if (!res.ok) {
        codeOutput.value = '';
        codeOutput.classList.remove('has-content');
        codeOutSize.textContent = '';
        codeLast = null;
        codeSetTip(codeErrorText(res), 'err');
        codeTip.title = res.detail || '';
        return;
    }
    codeLast = res;
    codeOutput.value = res.code;
    codeOutput.classList.add('has-content');
    codeOutSize.textContent = genT('genTipChars').replace('{n}', res.code.length.toLocaleString());
    codeSetTip(genT('genTipOk')
        .replace('{t}', String(res.types))
        .replace('{f}', String(res.fields)), 'ok');
    codeTip.title = '';
    codeOutBadge.textContent = CODE_LANG_LABEL[res.lang];
}

function codeSchedule() {
    clearTimeout(codeTimer);
    codeTimer = setTimeout(codeRegen, 180);
}

function codeLoadSample(name) {
    const text = codeSource === 'ddl'
        ? CODE_DDL_SAMPLE
        : (CODE_SAMPLES[name] || CODE_SAMPLES.user);
    codeSampleText = text;
    codeInput.value = text;
    codeRegen();
}

function codeSetSource(source) {
    if (source !== 'json' && source !== 'ddl') return;
    if (source === codeSource) return;
    codeSource = source;
    codeApplySourceUi();
    // 只有空着、或者当前内容还是上一次的示例时才自动换示例，别覆盖用户贴的数据
    if (!codeInput.value.trim() || codeInput.value === codeSampleText) {
        codeLoadSample('user');
    } else {
        codeRegen();
    }
}

function codeSetLang(lang) {
    if (!CODE_LANG_LABEL[lang] || lang === codeLang) return;
    codeLang = lang;
    codeOutBadge.textContent = CODE_LANG_LABEL[lang];
    codeLangTabs.querySelectorAll('.compare-tab').forEach((tab) => {
        tab.classList.toggle('active', tab.dataset.lang === lang);
    });
    codeSyncModes();
    codeRegen();
}

function codeFileName() {
    const code = codeOutput.value;
    const m = /(?:export interface|public class|class|type)\s+([A-Za-z_][A-Za-z0-9_]*)/.exec(code);
    const base = m ? m[1] : 'model';
    const snake = base.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
    if (codeLang === 'go' || codeLang === 'python') return snake + CODE_EXT[codeLang];
    return base + CODE_EXT[codeLang];
}

function enterCodeMode() {
    exitOtherModes('code');
    if (isDiffMode) {
        isDiffMode = false;
        diffReport.classList.remove('show');
        diffWorkspace.classList.remove('active');
        toggleDiffBtn.textContent = currentDict.diffBtn || '对比差异';
        toggleDiffBtn.classList.remove('btn-diff');
    }
    codeModeActive = true;
    markConvertActive(null);
    mainWorkspace.classList.add('hidden');
    toolbarEl.classList.add('hidden');
    // 先建编辑器再加 active：CM 在隐藏容器里量不到高度，会留一条“空条”给后续 refresh 收拾
    ensureCodeEditors();
    codeWorkspace.classList.add('active');
    navCodegenLink.classList.add('active');
    codeApplySourceUi();
    if (!codeInput.value.trim()) codeLoadSample('user');
    else codeRegen();
    requestAnimationFrame(() => {
        codeInputEditor.refresh();
        codeOutputEditor.refresh();
    });
}

function exitCodeMode() {
    if (!codeModeActive) return;
    codeModeActive = false;
    clearTimeout(codeTimer);
    codeWorkspace.classList.remove('active');
    navCodegenLink.classList.remove('active');
    toolbarEl.classList.remove('hidden');
    mainWorkspace.classList.remove('hidden');
    requestAnimationFrame(() => {
        inputEditor.refresh();
        outputEditor.refresh();
    });
}

function refreshCodeI18n() {
    codeApplySourceUi();
    if (codeModeActive) codeRegen();
}

